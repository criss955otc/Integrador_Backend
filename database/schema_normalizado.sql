-- ============================================================
-- Boquitas Sanas - esquema PostgreSQL normalizado
-- IDs autoincrementales (BIGINT / IDENTITY)
-- ============================================================
-- Ejecutar en Supabase > SQL Editor sobre una base de datos vacía.
-- IMPORTANTE: este script elimina las tablas del esquema anterior
-- para recrearlas con IDs numéricos autoincrementales.
-- ============================================================

DROP TABLE IF EXISTS citas CASCADE;
DROP TABLE IF EXISTS horarios_disponibles CASCADE;
DROP TABLE IF EXISTS servicios CASCADE;
DROP TABLE IF EXISTS pacientes CASCADE;
DROP TABLE IF EXISTS usuarios CASCADE;
DROP TABLE IF EXISTS estado_cita CASCADE;
DROP TABLE IF EXISTS estado_horario CASCADE;
DROP TABLE IF EXISTS rol_usuario CASCADE;

-- ============================================================
-- CATÁLOGOS
-- ============================================================

CREATE TABLE rol_usuario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL
);

CREATE TABLE estado_horario (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL
);

CREATE TABLE estado_cita (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(30) NOT NULL UNIQUE,
    nombre VARCHAR(80) NOT NULL
);

